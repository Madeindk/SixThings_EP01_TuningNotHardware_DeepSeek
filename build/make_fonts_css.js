/* Embeds the bundled OFL fonts as data URIs.
 *
 * Chrome refuses to load font files over file:// (they are fetched with CORS
 * semantics), so @font-face pointing at a path silently never loads and the
 * type falls back to a system font. Inlining the bytes removes the fetch
 * entirely and makes the render reproducible. */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const FONTS = path.resolve(__dirname, '..', 'SixThings_EP01', 'style', 'fonts');
const OUT = path.join(__dirname, 'renderer', 'fonts.css');

const faces = [
  ['BC', 'BarlowCondensed-ExtraBold.ttf', 800],
  ['BC', 'BarlowCondensed-Black.ttf', 900],
  ['IT', 'InterTight-VariableFont_wght.ttf', '100 900'],
  ['JM', 'JetBrainsMono-VariableFont_wght.ttf', '100 800'],
];

let css = '/* generated by make_fonts_css.js — do not edit */\n';
let total = 0;
for (const [family, file, weight] of faces) {
  const p = path.join(FONTS, file);
  if (!fs.existsSync(p)) { console.error('MISSING', p); process.exitCode = 1; continue; }
  const b64 = fs.readFileSync(p).toString('base64');
  total += b64.length;
  css += `@font-face{font-family:'${family}';font-weight:${weight};font-style:normal;` +
    `src:url(data:font/ttf;base64,${b64}) format('truetype');font-display:block}\n`;
  console.log(`  ${family} ${weight}  ${file}  ${(b64.length / 1024).toFixed(0)} kB`);
}
fs.writeFileSync(OUT, css, 'utf8');
console.log(`wrote ${OUT}  ${(total / 1024 / 1024).toFixed(2)} MB`);
